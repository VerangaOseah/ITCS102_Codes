#Operators
#Activity5

#Variables
a = 10
b = 5

#Addition
sum = a + b
print("The sum of",a,"and",b,"is",sum)

#Substraction
difference = a - b
print("The difference of",a,"and",b,"is",difference)

#Multiplication
product = a * b
print("The product of",a,"and",b,"is",product)

#Division
quotient = a / b
print("The quotient of",a,"and",b,"is", quotient)

#Floor Division
floordivision = a // b
print("The floordivison of",a,"and",b,"is",floordivision)

#Exponent
exponent = a ** b
print("10 to the 5th power is",exponent)

#Modulus 
modulus = a % b
print("Modulus of",a,"and",b,"is",modulus)

